import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const MAP_PATH = path.join(ROOT, 'data', 'tsa-image-ids.json');
const DB_PATH = path.join(ROOT, 'questionDatabase.js');
const OUT_DIR = path.join(ROOT, 'roblox', 'src', 'ReplicatedStorage', 'Modules');
const OUT_PATH = path.join(OUT_DIR, 'TSADatabase.luau');

// 確保輸出目錄存在
fs.mkdirSync(OUT_DIR, { recursive: true });

const mapData = JSON.parse(fs.readFileSync(MAP_PATH, 'utf8'));
const images = mapData.images || {};

const dbText = fs.readFileSync(DB_PATH, 'utf8');

// 用正則匹配 TSA_ALL 陣列內的所有物件
// 每個物件大致結構如：
// {
//     "Note": "TSA_ALL_1",
//     "rbxImageId": "rbxassetid://137144300741977",
//     "GUID": "2024TSA/TSA2024Q1",
//     ...
//     "C_A": "D",
//     ...
// }
const objRegex = /\{[\s\S]*?"GUID":\s*"((?:2024TSA|2025TSA)\/(TSA\d{4}Q\d+))"[\s\S]*?\}/g;

const results = {
  "2024TSA": {},
  "2025TSA": {}
};

let match;
while ((match = objRegex.exec(dbText)) !== null) {
  const objStr = match[0];
  const fullGuid = match[1]; // "2024TSA/TSA2024Q1"
  const qName = match[2];     // "TSA2024Q1"
  
  // 提取 C_A
  const caMatch = objStr.match(/"C_A":\s*"([A-D])"/);
  if (!caMatch) continue;
  const answer = caMatch[1];

  // 提取年分與題號，如 "2024TSA", "Q1"
  const year = fullGuid.split('/')[0]; // "2024TSA"
  const qNum = qName.match(/Q\d+/)?.[0]; // "Q1"

  if (!year || !qNum) continue;

  // 對照 imageId
  const rawId = images[qName];
  const imageId = rawId ? `rbxassetid://${rawId}` : `rbxgameasset://Images/${qName}`;

  results[year][qNum] = {
    ImageId: imageId,
    Answer: answer
  };
}

// 生成 Luau 格式代碼
const lines = [];
lines.push("-- Generated by tools/generate-tsa-database.mjs; do not edit by hand");
lines.push("return {");

for (const year of ["2024TSA", "2025TSA"]) {
  lines.push(`\t["${year}"] = {`);
  
  const qNums = Object.keys(results[year]).sort((a, b) => {
    const na = parseInt(a.slice(1));
    const nb = parseInt(b.slice(1));
    return na - nb;
  });

  for (const qNum of qNums) {
    const item = results[year][qNum];
    lines.push(`\t\t["${qNum}"] = { ImageId = "${item.ImageId}", Answer = "${item.Answer}" },`);
  }

  lines.push("\t},");
}

lines.push("}");

fs.writeFileSync(OUT_PATH, lines.join("\n") + "\n", 'utf8');
console.log(`成功生成 TSADatabase.luau => ${OUT_PATH}`);
